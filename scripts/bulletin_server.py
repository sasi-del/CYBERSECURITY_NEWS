app = Flask(__name__)

def load_data():
    news_path  = proj("data/news_latest.json")
    cache_path = proj("data/bulletin_cache.json")

    ai_summary = None
    if os.path.exists(cache_path):
        with open(cache_path, encoding="utf-8") as f:
            ai_summary = json.load(f).get("ai_summary")

    if not os.path.exists(news_path):
        return None, None, None, None, ai_summary

    with open(news_path, encoding="utf-8") as f:
        data = json.load(f)

    articles = data.get("articles", [])
    items    = cluster_articles(articles, top_n=25)
    sources  = source_breakdown(articles)
    sev_c    = severity_counts(items)
    stats    = {
        "total":    len(articles),
        "critical": sev_c["critical"],
        "high":     sev_c["high"],
        "medium":   sev_c["medium"],
        "low":      sev_c["low"],
    }
    updated = datetime.now().strftime("%Y-%m-%d %H:%M")
    return items, sources, stats, updated, ai_summary


@app.route("/")
def index():
    items, sources, stats, updated, ai_summary = load_data()
    if items is None:
        abort(503, description="data/news_latest.json not found — run collect_news.py first.")
    return render_template_string(HTML, items=items, sources=sources,
                                  stats=stats, updated=updated, ai_summary=ai_summary)


@app.route("/api/data")
def api_data():
    items, sources, stats, updated, ai_summary = load_data()
    if items is None:
        return jsonify({"error": "data not found"}), 503
    return jsonify({
        "updated":    updated,
        "stats":      stats,
        "ai_summary": ai_summary,
        "sources":    sources,
        "items": [{
            "title":    i["article"].get("title"),
            "url":      i["article"].get("url"),
            "source":   i["article"].get("source"),
            "published":i["article"].get("published"),
            "severity": i["severity"],
            "tags":     i["tags"],
            "score":    i["score"],
            "count":    i["count"],
            "cluster":  [{"title": c.get("title"), "url": c.get("url")} for c in i["cluster"]],
        } for i in items],
    })


